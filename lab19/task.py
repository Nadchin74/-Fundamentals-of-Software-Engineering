import threading
import time

# =====================================================================
# Завдання 2 та 3: Простий Singleton з лінивою ініціалізацією
# Об'єкт створюється лише тоді, коли ми вперше до нього звертаємось.
# =====================================================================
class SimpleLazySingleton:
    _instance = None

    def __new__(cls, *args, **kwargs):
        # Перевіряємо, чи екземпляр вже існує
        if cls._instance is None:
            print("[SimpleLazySingleton] Створення нового (єдиного) екземпляра...")
            cls._instance = super().__new__(cls)
        return cls._instance


# =====================================================================
# Завдання 4: Реалізація потокобезпечного Singleton
# Використовуємо блокування (Lock) та подвійну перевірку, щоб
# уникнути створення кількох об'єктів при паралельному виконанні.
# =====================================================================
class ThreadSafeSingleton:
    _instance = None
    _lock = threading.Lock()

    def __new__(cls, *args, **kwargs):
        if cls._instance is None:
            with cls._lock: # Блокуємо інші потоки
                if cls._instance is None:
                    print("[ThreadSafeSingleton] Створення потокобезпечного екземпляра...")
                    # Штучна затримка, щоб показати, що інші потоки чекають
                    time.sleep(0.1) 
                    cls._instance = super().__new__(cls)
        return cls._instance


# =====================================================================
# Завдання 5: Використання Singleton у реальному проекті
# Приклад: Глобальний менеджер налаштувань програми (Конфігурація).
# Наслідуємо потокобезпечний клас.
# =====================================================================
class AppConfig(ThreadSafeSingleton):
    def __init__(self):
        # Оскільки __init__ викликається щоразу при виклику AppConfig(),
        # нам треба захиститися від повторного перезапису даних.
        if not hasattr(self, 'initialized'):
            print("[AppConfig] Зчитування налаштувань з файлу (імітація)...")
            self.settings = {"theme": "dark", "language": "uk", "db_port": 5432}
            self.initialized = True


# =====================================================================
# Завдання 6: Порівняння з іншими підходами (Патерн Borg / Monostate)
# Це суто "пайтонівська" альтернатива Singleton.
# Замість одного об'єкта створюється багато, але всі вони ділять
# спільний словник атрибутів (спільний стан).
# =====================================================================
class Borg:
    _shared_state = {}  # Цей словник є спільним для ВСІХ екземплярів класу

    def __init__(self):
        # Підміняємо індивідуальний словник атрибутів об'єкта на спільний
        self.__dict__ = self._shared_state
        if not self._shared_state:
            print("[Borg] Ініціалізація спільного стану...")
            self.data = "Початкові дані"


